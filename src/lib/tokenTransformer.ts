// HELPER FUNCTIONS
// =============================================================================

function groupTokensByPath(tokens: DesignToken[]): Record<string, DesignToken[]> {
  const grouped: Record<string, DesignToken[]> = {};

  for (const token of tokens) {
    const pathKey = token.path.join('/');
    if (!grouped[pathKey]) {
      grouped[pathKey] = [];
    }
    grouped[pathKey].push(token);
  }

  return grouped;
}

function buildNestedObject(
  tokens: DesignToken[],
  colorScheme: ColorScheme
): Record<string, unknown> {
  const result: Record<string, unknown> = {};

  for (const token of tokens) {
    let current = result;

    for (const part of token.path) {
      if (!current[part]) {
        current[part] = {};
      }
      current = current[part] as Record<string, unknown>;
    }

    current[token.name] = colorScheme === 'dark' && token.value.darkValue
      ? token.value.darkValue
      : token.value.value;
  }

  return result;
}

function buildColorObject(
  tokens: DesignToken[],
  colorScheme: ColorScheme
): Record<string, unknown> {
  const result: Record<string, unknown> = {};

  for (const token of tokens) {
    const value = colorScheme === 'dark' && token.value.darkValue
      ? token.value.darkValue
      : token.value.value;

    // Handle nested colors (e.g., gray.500)
    const pathWithoutCategory = token.path.slice(1); // Remove 'color'
    let current = result;

    for (const part of pathWithoutCategory) {
      if (part === 'primitive' || part === 'semantic') continue;
      if (!current[part]) {
        current[part] = {};
      }
      current = current[part] as Record<string, unknown>;
    }

    // Extract shade from name (e.g., gray-500 -> 500)
    const nameParts = token.name.split('-');
    const shade = nameParts[nameParts.length - 1];

    if (/^\d+$/.test(shade)) {
      current[shade] = value;
    } else {
      current[token.name] = value;
    }
  }

  return result;
}

function formatObjectContent(obj: Record<string, unknown>, indent: number): string {
  const lines: string[] = [];
  const spaces = ' '.repeat(indent);

  for (const [key, value] of Object.entries(obj)) {
    if (typeof value === 'object' && value !== null) {
      lines.push(`${spaces}'${key}': {`);
      lines.push(formatObjectContent(value as Record<string, unknown>, indent + 2));
      lines.push(`${spaces}},`);
    } else {
      lines.push(`${spaces}'${key}': '${value}',`);
    }
  }

  return lines.join('\n');
}

function mapTypeToFigma(type: string): string {
  const typeMap: Record<string, string> = {
    color: 'color',
    fontSize: 'fontSizes',
    fontFamily: 'fontFamilies',
    fontWeight: 'fontWeights',
    lineHeight: 'lineHeights',
    letterSpacing: 'letterSpacing',
    spacing: 'spacing',
    borderRadius: 'borderRadius',
    borderWidth: 'borderWidth',
    shadow: 'boxShadow',
    opacity: 'opacity',
    duration: 'motion',
    easing: 'motion',
    dimension: 'sizing',
  };

  return typeMap[type] || 'other';
}

function hexToRgb(hex: string): { r: number; g: number; b: number } | null {
  const shorthandRegex = /^#?([a-f\d])([a-f\d])([a-f\d])$/i;
  const expandedHex = hex.replace(shorthandRegex, (_, r, g, b) => r + r + g + g + b + b);

  const result = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(expandedHex);
  return result
    ? {
        r: parseInt(result[1], 16),
        g: parseInt(result[2], 16),
        b: parseInt(result[3], 16),
      }
    : null;
}

function camelCase(str: string): string {
  return str
    .replace(/[-_](.)/g, (_, char) => char.toUpperCase())
    .replace(/^(.)/, (_, char) => char.toLowerCase());
}

function escapeXml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

