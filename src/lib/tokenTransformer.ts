// TAILWIND CONFIG TRANSFORMER
// =============================================================================

function transformToTailwind(
  tokens: DesignToken[],
  options: TransformOptions
): TransformResult {
  const { colorScheme = 'light' } = options;
  const lines: string[] = [];

  lines.push('/** @type {import("tailwindcss").Config} */');
  lines.push('module.exports = {');
  lines.push('  theme: {');
  lines.push('    extend: {');

  // Colors
  const colorTokens = tokens.filter(t => t.category === 'color');
  if (colorTokens.length > 0) {
    lines.push('      colors: {');
    const colorObj = buildColorObject(colorTokens, colorScheme);
    lines.push(formatObjectContent(colorObj, 8));
    lines.push('      },');
  }

  // Spacing
  const spacingTokens = tokens.filter(t => t.category === 'spacing');
  if (spacingTokens.length > 0) {
    lines.push('      spacing: {');
    for (const token of spacingTokens) {
      const key = token.name.replace('spacing-', '');
      lines.push(`        '${key}': '${token.value.value}',`);
    }
    lines.push('      },');
  }

  // Font Size
  const fontSizeTokens = tokens.filter(t => t.type === 'fontSize');
  if (fontSizeTokens.length > 0) {
    lines.push('      fontSize: {');
    for (const token of fontSizeTokens) {
      const key = token.name.replace('font-size-', '');
      lines.push(`        '${key}': '${token.value.value}',`);
    }
    lines.push('      },');
  }

  // Font Weight
  const fontWeightTokens = tokens.filter(t => t.type === 'fontWeight');
  if (fontWeightTokens.length > 0) {
    lines.push('      fontWeight: {');
    for (const token of fontWeightTokens) {
      const key = token.name.replace('font-weight-', '');
      lines.push(`        '${key}': '${token.value.value}',`);
    }
    lines.push('      },');
  }

  // Border Radius
  const radiusTokens = tokens.filter(t => t.type === 'borderRadius');
  if (radiusTokens.length > 0) {
    lines.push('      borderRadius: {');
    for (const token of radiusTokens) {
      const key = token.name.replace('border-radius-', '');
      lines.push(`        '${key}': '${token.value.value}',`);
    }
    lines.push('      },');
  }

  // Box Shadow
  const shadowTokens = tokens.filter(t => t.category === 'shadow');
  if (shadowTokens.length > 0) {
    lines.push('      boxShadow: {');
    for (const token of shadowTokens) {
      const key = token.name.replace('shadow-', '');
      lines.push(`        '${key}': '${token.value.value}',`);
    }
    lines.push('      },');
  }

  // Z-Index
  const zIndexTokens = tokens.filter(t => t.category === 'zIndex');
  if (zIndexTokens.length > 0) {
    lines.push('      zIndex: {');
    for (const token of zIndexTokens) {
      const key = token.name.replace('z-index-', '');
      lines.push(`        '${key}': '${token.value.value}',`);
    }
    lines.push('      },');
  }

  // Animation
  const durationTokens = tokens.filter(t => t.type === 'duration');
  if (durationTokens.length > 0) {
    lines.push('      transitionDuration: {');
    for (const token of durationTokens) {
      const key = token.name.replace('duration-', '');
      lines.push(`        '${key}': '${token.value.value}',`);
    }
    lines.push('      },');
  }

  // Screens (breakpoints)
  const breakpointTokens = tokens.filter(t => t.category === 'breakpoint');
  if (breakpointTokens.length > 0) {
    lines.push('      screens: {');
    for (const token of breakpointTokens) {
      const key = token.name.replace('breakpoint-', '');
      if (key !== 'xs') { // xs is usually not needed in Tailwind
        lines.push(`        '${key}': '${token.value.value}',`);
      }
    }
    lines.push('      },');
  }

  lines.push('    },');
  lines.push('  },');
  lines.push('};');

  return {
    format: 'tailwind',
    content: lines.join('\n'),
    filename: 'tailwind.config.js',
    mimeType: 'text/javascript',
  };
}

// =============================================================================
// iOS SWIFT TRANSFORMER
// =============================================================================

function transformToiOS(
  tokens: DesignToken[],
  options: TransformOptions
): TransformResult {
  const { colorScheme = 'light' } = options;
  const lines: string[] = [];

  lines.push('import SwiftUI');
  lines.push('');
  lines.push('// Design Tokens');
  lines.push('// Generated by Tailwind Builder');
  lines.push('');

  // Colors
  const colorTokens = tokens.filter(t => t.category === 'color');
  if (colorTokens.length > 0) {
    lines.push('extension Color {');
    lines.push('    struct DesignTokens {');

    for (const token of colorTokens) {
      const value = colorScheme === 'dark' && token.value.darkValue
        ? token.value.darkValue
        : token.value.value;

      if (typeof value === 'string' && value.startsWith('#')) {
        const rgb = hexToRgb(value);
        if (rgb) {
          const swiftName = camelCase(token.name);
          lines.push(`        static let ${swiftName} = Color(red: ${(rgb.r / 255).toFixed(3)}, green: ${(rgb.g / 255).toFixed(3)}, blue: ${(rgb.b / 255).toFixed(3)})`);
        }
      }
    }

    lines.push('    }');
    lines.push('}');
    lines.push('');
  }

  // Spacing
  const spacingTokens = tokens.filter(t => t.category === 'spacing');
  if (spacingTokens.length > 0) {
    lines.push('struct Spacing {');

    for (const token of spacingTokens) {
      const value = parseFloat(String(token.value.value));
      const pxValue = token.value.value.toString().includes('rem')
        ? value * 16
        : value;
      const swiftName = camelCase(token.name.replace('spacing-', 'space'));
      lines.push(`    static let ${swiftName}: CGFloat = ${pxValue}`);
    }

    lines.push('}');
    lines.push('');
  }

  // Typography
  const fontSizeTokens = tokens.filter(t => t.type === 'fontSize');
  if (fontSizeTokens.length > 0) {
    lines.push('struct Typography {');
    lines.push('    struct Size {');

    for (const token of fontSizeTokens) {
      const value = parseFloat(String(token.value.value));
      const ptValue = token.value.value.toString().includes('rem')
        ? value * 16
        : value;
      const swiftName = camelCase(token.name.replace('font-size-', ''));
      lines.push(`        static let ${swiftName}: CGFloat = ${ptValue}`);
    }

    lines.push('    }');
    lines.push('}');
    lines.push('');
  }

  // Border Radius
  const radiusTokens = tokens.filter(t => t.type === 'borderRadius');
  if (radiusTokens.length > 0) {
    lines.push('struct CornerRadius {');

    for (const token of radiusTokens) {
      if (token.value.value !== '9999px') {
        const value = parseFloat(String(token.value.value));
        const pxValue = token.value.value.toString().includes('rem')
          ? value * 16
          : value;
        const swiftName = camelCase(token.name.replace('border-radius-', ''));
        lines.push(`    static let ${swiftName}: CGFloat = ${pxValue}`);
      }
    }

    lines.push('}');
  }

  return {
    format: 'ios',
    content: lines.join('\n'),
    filename: 'DesignTokens.swift',
    mimeType: 'text/x-swift',
  };
}

// =============================================================================
// ANDROID XML TRANSFORMER
// =============================================================================

function transformToAndroid(
  tokens: DesignToken[],
  options: TransformOptions
): TransformResult {
  const { colorScheme = 'light' } = options;
  const lines: string[] = [];

  lines.push('<?xml version="1.0" encoding="utf-8"?>');
  lines.push('<!-- Design Tokens - Generated by Tailwind Builder -->');
  lines.push('<resources>');
  lines.push('');

  // Colors
  const colorTokens = tokens.filter(t => t.category === 'color');
  if (colorTokens.length > 0) {
    lines.push('    <!-- Colors -->');

    for (const token of colorTokens) {
      const value = colorScheme === 'dark' && token.value.darkValue
        ? token.value.darkValue
        : token.value.value;

      if (typeof value === 'string' && value.startsWith('#')) {
        const androidName = token.path.join('_') + '_' + token.name;
        const androidColor = value.length === 4
          ? `#${value[1]}${value[1]}${value[2]}${value[2]}${value[3]}${value[3]}`
          : value;
        lines.push(`    <color name="${androidName}">${androidColor}</color>`);
      }
    }
    lines.push('');
  }

  // Dimensions (spacing, font sizes, border radius)
  const dimensionTokens = tokens.filter(t =>
    t.category === 'spacing' ||
    t.type === 'fontSize' ||
    t.type === 'borderRadius'
  );

  if (dimensionTokens.length > 0) {
    lines.push('    <!-- Dimensions -->');

    for (const token of dimensionTokens) {
      const value = String(token.value.value);
      let dpValue: string;

      if (value.includes('rem')) {
        dpValue = `${parseFloat(value) * 16}dp`;
      } else if (value.includes('px')) {
        dpValue = `${parseFloat(value)}dp`;
      } else if (value === '9999px') {
        dpValue = '9999dp';
      } else {
        dpValue = `${parseFloat(value)}dp`;
      }

      const androidName = token.path.join('_') + '_' + token.name;
      lines.push(`    <dimen name="${androidName}">${dpValue}</dimen>`);
    }
    lines.push('');
  }

  // Integers (z-index, opacity as percentage, font weight)
  const integerTokens = tokens.filter(t =>
    t.category === 'zIndex' ||
    t.type === 'fontWeight'
  );

  if (integerTokens.length > 0) {
    lines.push('    <!-- Integers -->');

    for (const token of integerTokens) {
      const value = String(token.value.value);
      if (value !== 'auto') {
        const androidName = token.path.join('_') + '_' + token.name;
        lines.push(`    <integer name="${androidName}">${value}</integer>`);
      }
    }
    lines.push('');
  }

  // Strings (font family, easing)
  const stringTokens = tokens.filter(t =>
    t.type === 'fontFamily' ||
    t.type === 'easing' ||
    t.type === 'shadow'
  );

  if (stringTokens.length > 0) {
    lines.push('    <!-- Strings -->');

    for (const token of stringTokens) {
      const androidName = token.path.join('_') + '_' + token.name;
      const value = String(token.value.value).replace(/"/g, '\\"');
      lines.push(`    <string name="${androidName}">${escapeXml(value)}</string>`);
    }
    lines.push('');
  }

  lines.push('</resources>');

  return {
    format: 'android',
    content: lines.join('\n'),
    filename: 'design_tokens.xml',
    mimeType: 'application/xml',
  };
}

// =============================================================================
// MAIN TRANSFORMER
// =============================================================================

/**
 * Transform tokens to the specified format
 */
export function transformTokens(
  tokens: DesignToken[],
  options: TransformOptions
): TransformResult {
  // Filter by categories if specified
  let filteredTokens = tokens;
  if (options.categories && options.categories.length > 0) {
    filteredTokens = tokens.filter(t => options.categories!.includes(t.category));
  }

  switch (options.format) {
    case 'css':
      return transformToCSS(filteredTokens, options);
    case 'scss':
      return transformToSCSS(filteredTokens, options);
    case 'js':
      return transformToJS(filteredTokens, { ...options, typescript: false });
    case 'ts':
      return transformToJS(filteredTokens, { ...options, typescript: true });
    case 'json':
      return transformToJSON(filteredTokens, options);
    case 'figma':
      return transformToFigma(filteredTokens, options);
    case 'tailwind':
      return transformToTailwind(filteredTokens, options);
    case 'ios':
      return transformToiOS(filteredTokens, options);
    case 'android':
      return transformToAndroid(filteredTokens, options);
    default:
      throw new Error(`Unsupported format: ${options.format}`);
  }
}

/**
 * Transform entire token collection
 */
export function transformCollection(
  collection: TokenCollection,
  options: TransformOptions
): TransformResult {
  return transformTokens(collection.tokens, options);
}

/**
 * Transform tokens to all supported formats
 */
export function transformToAllFormats(
  tokens: DesignToken[],
  options: Omit<TransformOptions, 'format'>
): TransformResult[] {
  const formats: TokenFormat[] = [
    'css',
    'scss',
    'js',
    'ts',
    'json',
    'figma',
    'tailwind',
    'ios',
    'android',
  ];

  return formats.map(format => transformTokens(tokens, { ...options, format }));
}

