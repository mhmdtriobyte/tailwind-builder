/**
 * Token Transformer
 *
 * Transforms design tokens into multiple output formats:
 * CSS, SCSS, JavaScript, JSON, Figma, Tailwind, iOS, Android
 */

import type {
  DesignToken,
  TokenCollection,
  TokenFormat,
  TokenCategory,
  ColorScheme,
} from './designTokens';
import { getTokenPath, tokenToCssVarName } from './designTokens';

// =============================================================================
// TRANSFORMER OPTIONS
// =============================================================================

export interface TransformOptions {
  format: TokenFormat;
  colorScheme?: ColorScheme;
  includeMeta?: boolean;
  prefix?: string;
  indent?: string;
  outputMode?: 'flat' | 'nested';
  categories?: TokenCategory[];
}

export interface TransformResult {
  format: TokenFormat;
  content: string;
  filename: string;
  mimeType: string;
}

// =============================================================================
// CSS TRANSFORMER
// =============================================================================

function transformToCSS(
  tokens: DesignToken[],
  options: TransformOptions
): TransformResult {
  const { colorScheme = 'light', prefix = '', indent = '  ' } = options;
  const lines: string[] = [];

  // Group tokens by path for better organization
  const groupedTokens = groupTokensByPath(tokens);

  lines.push(':root {');

  for (const [path, pathTokens] of Object.entries(groupedTokens)) {
    if (options.includeMeta) {
      lines.push(`${indent}/* ${path} */`);
    }

    for (const token of pathTokens) {
      const varName = prefix
        ? `--${prefix}-${token.path.join('-')}-${token.name}`
        : tokenToCssVarName(token);

      const value = colorScheme === 'dark' && token.value.darkValue
        ? token.value.darkValue
        : token.value.value;

      if (options.includeMeta && token.metadata?.description) {
        lines.push(`${indent}/* ${token.metadata.description} */`);
      }

      lines.push(`${indent}${varName}: ${value};`);
    }

    lines.push('');
  }

  lines.push('}');

  // Add dark mode variant
  if (colorScheme === 'light') {
    const darkTokens = tokens.filter(t => t.value.darkValue);
    if (darkTokens.length > 0) {
      lines.push('');
      lines.push('@media (prefers-color-scheme: dark) {');
      lines.push(`${indent}:root {`);

      for (const token of darkTokens) {
        const varName = prefix
          ? `--${prefix}-${token.path.join('-')}-${token.name}`
          : tokenToCssVarName(token);
        lines.push(`${indent}${indent}${varName}: ${token.value.darkValue};`);
      }

      lines.push(`${indent}}`);
      lines.push('}');

      // Also add .dark class variant
      lines.push('');
      lines.push('.dark {');

      for (const token of darkTokens) {
        const varName = prefix
          ? `--${prefix}-${token.path.join('-')}-${token.name}`
          : tokenToCssVarName(token);
        lines.push(`${indent}${varName}: ${token.value.darkValue};`);
      }

      lines.push('}');
    }
  }

  return {
    format: 'css',
    content: lines.join('\n'),
    filename: 'tokens.css',
    mimeType: 'text/css',
  };
}

// =============================================================================
// SCSS TRANSFORMER
// =============================================================================

function transformToSCSS(
  tokens: DesignToken[],
  options: TransformOptions
): TransformResult {
  const { colorScheme = 'light', prefix = '', includeMeta = false } = options;
  const lines: string[] = [];

  // SCSS variables
  lines.push('// Design Tokens - SCSS Variables');
  lines.push('// Generated by Tailwind Builder');
  lines.push('');

  const groupedTokens = groupTokensByPath(tokens);

  for (const [path, pathTokens] of Object.entries(groupedTokens)) {
    lines.push(`// ${path}`);

    for (const token of pathTokens) {
      const varName = prefix
        ? `$${prefix}-${token.path.join('-')}-${token.name}`
        : `$${token.path.join('-')}-${token.name}`;

      const value = colorScheme === 'dark' && token.value.darkValue
        ? token.value.darkValue
        : token.value.value;

      if (includeMeta && token.metadata?.description) {
        lines.push(`// ${token.metadata.description}`);
      }

      lines.push(`${varName}: ${value};`);
    }

    lines.push('');
  }

  // Add a map for easier access
  lines.push('// Token Maps');
  lines.push('$tokens: (');

  for (const [path, pathTokens] of Object.entries(groupedTokens)) {
    lines.push(`  "${path}": (`);
    for (const token of pathTokens) {
      const value = colorScheme === 'dark' && token.value.darkValue
        ? token.value.darkValue
        : token.value.value;
      lines.push(`    "${token.name}": ${value},`);
    }
    lines.push('  ),');
  }

  lines.push(');');

  // Add utility function
  lines.push('');
  lines.push('// Utility function to get token value');
  lines.push('@function token($path, $name) {');
  lines.push('  @if map-has-key($tokens, $path) {');
  lines.push('    $group: map-get($tokens, $path);');
  lines.push('    @if map-has-key($group, $name) {');
  lines.push('      @return map-get($group, $name);');
  lines.push('    }');
  lines.push('  }');
  lines.push('  @warn "Token not found: #{$path}/#{$name}";');
  lines.push('  @return null;');
  lines.push('}');

  return {
    format: 'scss',
    content: lines.join('\n'),
    filename: 'tokens.scss',
    mimeType: 'text/x-scss',
  };
}

// =============================================================================
// JAVASCRIPT/TYPESCRIPT TRANSFORMER
// =============================================================================

function transformToJS(
  tokens: DesignToken[],
  options: TransformOptions & { typescript?: boolean }
): TransformResult {
  const { colorScheme = 'light', prefix = '', typescript = false } = options;
  const lines: string[] = [];

  if (typescript) {
    lines.push('/**');
    lines.push(' * Design Tokens');
    lines.push(' * Generated by Tailwind Builder');
    lines.push(' */');
    lines.push('');
    lines.push('export interface TokenValue {');
    lines.push('  value: string;');
    lines.push('  darkValue?: string;');
    lines.push('}');
    lines.push('');
  }

  // Build nested object
  const tokenObj = buildNestedObject(tokens, colorScheme);

  const objName = prefix ? `${prefix}Tokens` : 'tokens';

  if (typescript) {
    lines.push(`export const ${objName} = ${JSON.stringify(tokenObj, null, 2)} as const;`);
    lines.push('');
    lines.push(`export type TokenPath = keyof typeof ${objName};`);
  } else {
    lines.push(`export const ${objName} = ${JSON.stringify(tokenObj, null, 2)};`);
  }

  lines.push('');

  // Add helper functions
  lines.push('/**');
  lines.push(' * Get token value by path');
  lines.push(' * @example getToken("color.primitive.blue.500")');
  lines.push(' */');

  if (typescript) {
    lines.push(`export function getToken(path: string): string | undefined {`);
  } else {
    lines.push(`export function getToken(path) {`);
  }

  lines.push(`  const parts = path.split('.');`);
  lines.push(`  let current = ${objName};`);
  lines.push('  for (const part of parts) {');
  lines.push('    if (current && typeof current === "object" && part in current) {');
  lines.push('      current = current[part];');
  lines.push('    } else {');
  lines.push('      return undefined;');
  lines.push('    }');
  lines.push('  }');
  lines.push('  return typeof current === "string" ? current : undefined;');
  lines.push('}');

  return {
    format: typescript ? 'ts' : 'js',
    content: lines.join('\n'),
    filename: typescript ? 'tokens.ts' : 'tokens.js',
    mimeType: typescript ? 'text/typescript' : 'text/javascript',
  };
}

// =============================================================================
// JSON TRANSFORMER (Style Dictionary Format)
// =============================================================================

function transformToJSON(
  tokens: DesignToken[],
  options: TransformOptions
): TransformResult {
  const { colorScheme = 'light', includeMeta = true } = options;

  const styleDictionaryTokens: Record<string, unknown> = {};

  for (const token of tokens) {
    let current = styleDictionaryTokens;

    // Navigate/create nested structure
    for (const part of token.path) {
      if (!current[part]) {
        current[part] = {};
      }
      current = current[part] as Record<string, unknown>;
    }

    // Add token
    const tokenData: Record<string, unknown> = {
      value: colorScheme === 'dark' && token.value.darkValue
        ? token.value.darkValue
        : token.value.value,
      type: token.type,
    };

    if (includeMeta) {
      if (token.metadata?.description) {
        tokenData.description = token.metadata.description;
      }
      if (token.reference) {
        tokenData.$reference = token.reference;
      }
      if (token.value.darkValue) {
        tokenData.$darkValue = token.value.darkValue;
      }
    }

    current[token.name] = tokenData;
  }

  return {
    format: 'json',
    content: JSON.stringify(styleDictionaryTokens, null, 2),
    filename: 'tokens.json',
    mimeType: 'application/json',
  };
}

// =============================================================================
// FIGMA TOKENS TRANSFORMER
// =============================================================================

function transformToFigma(
  tokens: DesignToken[],
  options: TransformOptions
): TransformResult {
  const { colorScheme = 'light' } = options;

  const figmaTokens: Record<string, unknown> = {
    global: {},
  };

  const global = figmaTokens.global as Record<string, unknown>;

  for (const token of tokens) {
    let current = global;

    // Create nested path
    for (const part of token.path) {
      if (!current[part]) {
        current[part] = {};
      }
      current = current[part] as Record<string, unknown>;
    }

    const value = colorScheme === 'dark' && token.value.darkValue
      ? token.value.darkValue
      : token.value.value;

    // Figma tokens format
    current[token.name] = {
      value,
      type: mapTypeToFigma(token.type),
      ...(token.metadata?.description && { description: token.metadata.description }),
    };
  }

  // Add dark mode as separate set if applicable
  const darkTokens = tokens.filter(t => t.value.darkValue);
  if (darkTokens.length > 0) {
    figmaTokens.dark = {};
    const dark = figmaTokens.dark as Record<string, unknown>;

    for (const token of darkTokens) {
      let current = dark;

      for (const part of token.path) {
        if (!current[part]) {
          current[part] = {};
        }
        current = current[part] as Record<string, unknown>;
      }

      current[token.name] = {
        value: token.value.darkValue,
        type: mapTypeToFigma(token.type),
      };
    }
  }

  return {
    format: 'figma',
    content: JSON.stringify(figmaTokens, null, 2),
    filename: 'figma-tokens.json',
    mimeType: 'application/json',
  };
}

